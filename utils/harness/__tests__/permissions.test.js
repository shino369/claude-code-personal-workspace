import fs from 'fs';
import path from 'path';
import { ROOT_DIR } from '#utils/workspace-config.js';
import {
  commandMatch,
  guardDecision,
  pathMatches,
  readPermissions,
  renderCodexRules,
} from '../permissions.js';

const SETTINGS = {
  permissions: {
    deny: [
      'Read(./.env)',
      'Read(./.env.*)',
      'Read(~/.ssh/**)',
      'Edit(./secrets/**)',
      'Edit(./**/*.pem)',
      'Bash(rm:*)',
      'Bash(npm *)',
      'Bash(git push --force:*)',
      'WebFetch(domain:example.com)',
      'Bash(weird',
    ],
    ask: ['Bash(git push:*)', 'Bash(kill -9:*)', 'Read(./notes.md)'],
  },
};
const PERMS = readPermissions(SETTINGS);
const where = { projectDir: '/proj', home: '/home/me' };

describe('readPermissions', () => {
  test('should sort the rules it can enforce outside Claude Code', () => {
    expect(PERMS).toEqual({
      deny: {
        commands: [['rm'], ['npm'], ['git', 'push', '--force']],
        read: ['./.env', './.env.*', '~/.ssh/**'],
        edit: ['./secrets/**', './**/*.pem'],
      },
      ask: {
        commands: [
          ['git', 'push'],
          ['kill', '-9'],
        ],
      },
    });
  });

  test('should find no rules in settings without permissions', () => {
    const none = {
      deny: { commands: [], read: [], edit: [] },
      ask: { commands: [] },
    };
    expect(readPermissions({})).toEqual(none);
    expect(readPermissions(null)).toEqual(none);
    expect(readPermissions({ permissions: { deny: 'x', ask: [3] } })).toEqual(
      none
    );
  });
});

describe('renderCodexRules', () => {
  test('should turn denied commands into forbidden rules and asked ones into prompt rules', () => {
    const text = renderCodexRules(PERMS);
    expect(text.startsWith('# Generated by pnpm harness sync')).toBe(true);
    expect(text).toContain(`prefix_rule(
    pattern = ["rm"],
    decision = "forbidden",
    justification = "Use pnpm task rm <path> instead: it moves files to tasks/.trash/ (AGENTS.md §1).",
)`);
    expect(text).toContain(`    pattern = ["git", "push", "--force"],
    decision = "forbidden",`);
    expect(text).toContain(`    pattern = ["kill", "-9"],
    decision = "prompt",
    justification = "Ask the user first (.claude/settings.json permissions.ask; AGENTS.md §1).",`);
    expect(text).toContain(
      'justification = "Use pnpm instead (AGENTS.md §1).",'
    );
    expect(text.endsWith(')\n')).toBe(true);
  });

  test('should write only the header when there are no command rules', () => {
    expect(
      renderCodexRules(readPermissions({})).trim().split('\n')
    ).toHaveLength(2);
  });
});

describe('commandMatch', () => {
  const prefixes = [['rm'], ['git', 'push'], ['npm']];

  test('should match a command by its leading words', () => {
    expect(commandMatch('rm -rf build', prefixes)).toEqual(['rm']);
    expect(commandMatch('git push origin main', prefixes)).toEqual([
      'git',
      'push',
    ]);
    expect(commandMatch('git status', prefixes)).toBeNull();
    expect(commandMatch('npmx', prefixes)).toBeNull();
  });

  test('should check each part of a compound command', () => {
    expect(commandMatch('ls && rm x', prefixes)).toEqual(['rm']);
    expect(commandMatch('cat a | npm i', prefixes)).toEqual(['npm']);
    expect(commandMatch('echo hi; git push', prefixes)).toEqual([
      'git',
      'push',
    ]);
    expect(commandMatch('false || rm y', prefixes)).toEqual(['rm']);
  });

  test('should skip leading variable assignments and look inside sh -c', () => {
    expect(commandMatch('FOO=1 BAR=2 rm x', prefixes)).toEqual(['rm']);
    expect(commandMatch(`bash -lc 'rm -rf x'`, prefixes)).toEqual(['rm']);
    expect(commandMatch(`sh -c "git push"`, prefixes)).toEqual(['git', 'push']);
  });

  test('should treat a bare shell name as an ordinary command', () => {
    expect(commandMatch('bash', [['bash']])).toEqual(['bash']);
    expect(commandMatch('bash script.sh', prefixes)).toBeNull();
  });

  test('should not read a heredoc body as commands', () => {
    const format = [['format'], ['rm']];
    expect(
      commandMatch(
        'git commit -m "$(cat <<\'EOF\'\nformat output\nEOF\n)"',
        format
      )
    ).toBeNull();
    expect(
      commandMatch("cat > a.md <<'EOF'\nformat the output\nEOF", format)
    ).toBeNull();
    expect(commandMatch('cat <<-END\n\tformat x\n\tEND', format)).toBeNull();
    expect(commandMatch('cat <<"X"\nrm x\nX', format)).toBeNull();
  });

  test('should see the commands after a heredoc, whatever its body holds', () => {
    expect(commandMatch("cat <<EOF\ndon't\nEOF\nrm -rf x", prefixes)).toEqual([
      'rm',
    ]);
    expect(commandMatch('cat <<A <<B\na\nA\nb\nB\nrm y', prefixes)).toEqual([
      'rm',
    ]);
  });

  test('should treat an unterminated heredoc as running to the end, as bash does', () => {
    expect(commandMatch('cat <<EOF\nrm -rf x', prefixes)).toBeNull();
  });

  test('should not take a here-string or a quoted << for a heredoc', () => {
    expect(commandMatch("cat <<< 'x'\nrm y", prefixes)).toEqual(['rm']);
    expect(commandMatch("echo '<<X'\nrm y\nX", prefixes)).toEqual(['rm']);
  });

  test('should not match empty commands', () => {
    expect(commandMatch('', prefixes)).toBeNull();
    expect(commandMatch('   ', prefixes)).toBeNull();
  });
});

describe('pathMatches', () => {
  test('should anchor ./ at the project and ~/ at home', () => {
    expect(pathMatches('/proj/.env', './.env', where)).toBe(true);
    expect(pathMatches('/proj/sub/.env', './.env', where)).toBe(false);
    expect(pathMatches('/home/me/.ssh/id_rsa', '~/.ssh/**', where)).toBe(true);
  });

  test('should treat * as one path segment and ** as any depth', () => {
    expect(pathMatches('/proj/.env.local', './.env.*', where)).toBe(true);
    expect(pathMatches('/proj/.env.d/x', './.env.*', where)).toBe(false);
    expect(pathMatches('/proj/a/b/key.pem', './**/*.pem', where)).toBe(true);
    expect(pathMatches('/proj/key.pem', './**/*.pem', where)).toBe(true);
    expect(pathMatches('/proj/secrets/a/b', './secrets/**', where)).toBe(true);
  });

  test('should read // as an absolute path and escape regex characters', () => {
    expect(
      pathMatches('C:/Program Files/x', '//C:/Program Files/**', where)
    ).toBe(true);
    expect(pathMatches('/proj/a+b.key', './a+b.key', where)).toBe(true);
    expect(pathMatches('/proj/aab.key', './a+b.key', where)).toBe(false);
  });

  test('should take a pattern without ./, ~/, or // as it is', () => {
    expect(pathMatches('/etc/passwd', '/etc/passwd', where)).toBe(true);
  });

  test('should compare Windows paths with forward slashes', () => {
    expect(
      pathMatches('C:\\proj\\.env', './.env', {
        projectDir: 'C:\\proj',
        home: '',
      })
    ).toBe(true);
  });
});

describe('guardDecision', () => {
  /**
   * @param {Record<string, unknown>} input
   * @param {import('../input.js').Harness} [harness]
   */
  const decide = (input, harness = 'dsh') =>
    guardDecision({ cwd: '/proj', ...input }, PERMS, { harness, ...where });

  test('should deny an edit or a patch that touches a protected path', () => {
    expect(
      decide({ tool_name: 'edit', tool_input: { file_path: 'secrets/a.txt' } })
    ).toEqual({
      decision: 'deny',
      reason:
        'secrets/a.txt is protected in this workspace (.claude/settings.json permissions.deny Edit(./secrets/**); AGENTS.md §1).',
    });
    expect(
      decide(
        {
          tool_name: 'Bash',
          tool_input: {
            command:
              "apply_patch <<'EOF'\n*** Begin Patch\n*** Add File: certs/x.pem\n*** End Patch\nEOF",
          },
        },
        'codex'
      )?.decision
    ).toBe('deny');
  });

  test('should resolve . and .. and doubled slashes in relative paths', () => {
    for (const file of ['./secrets/a', 'x/../secrets/a', 'secrets//a']) {
      expect(
        decide({ tool_name: 'edit', tool_input: { file_path: file } })?.decision
      ).toBe('deny');
    }
    expect(
      decide({
        tool_name: 'edit',
        tool_input: { file_path: '../proj2/secrets/a' },
      })
    ).toBeNull();
  });

  test('should resolve relative paths against the project when there is no cwd', () => {
    expect(
      guardDecision(
        { tool_name: 'edit', tool_input: { file_path: 'secrets/a' } },
        PERMS,
        { harness: 'dsh', ...where }
      )?.decision
    ).toBe('deny');
  });

  test('should deny reading a protected path', () => {
    expect(
      decide({ tool_name: 'read', tool_input: { file_path: '/proj/.env' } })
    ).toMatchObject({ decision: 'deny' });
    expect(
      decide({ tool_name: 'read', tool_input: { file_path: 'README.md' } })
    ).toBeNull();
  });

  test('should deny or ask for DSH shell commands from the same lists', () => {
    expect(
      decide({ tool_name: 'bash', tool_input: { command: 'rm -rf x' } })
    ).toEqual({
      decision: 'deny',
      reason:
        'Use pnpm task rm <path> instead: it moves files to tasks/.trash/ (AGENTS.md §1).',
    });
    expect(
      decide({ tool_name: 'bash', tool_input: { command: 'git push' } })
    ).toEqual({
      decision: 'ask',
      reason:
        'Ask the user first (.claude/settings.json permissions.ask; AGENTS.md §1).',
    });
    expect(
      decide({ tool_name: 'bash', tool_input: { command: 'git push --force' } })
    ).toMatchObject({ decision: 'deny' });
    expect(
      decide({ tool_name: 'bash', tool_input: { command: 'ls' } })
    ).toBeNull();
  });

  test("should leave Codex shell commands to Codex's own rules", () => {
    expect(
      decide(
        { tool_name: 'Bash', tool_input: { command: 'rm -rf x' } },
        'codex'
      )
    ).toBeNull();
  });

  test('should allow other tools and edits elsewhere', () => {
    expect(decide({ tool_name: 'WebFetch', tool_input: {} })).toBeNull();
    expect(
      decide({ tool_name: 'write', tool_input: { file_path: 'src/a.js' } })
    ).toBeNull();
  });
});

describe('the committed rules', () => {
  test('should match .claude/settings.json (run pnpm harness sync)', () => {
    const settings = JSON.parse(
      fs.readFileSync(path.join(ROOT_DIR, '.claude/settings.json'), 'utf-8')
    );
    expect(
      fs.readFileSync(
        path.join(ROOT_DIR, '.codex/rules/workspace.rules'),
        'utf-8'
      )
    ).toBe(renderCodexRules(readPermissions(settings)));
  });
});
