import fs from 'fs';
import os from 'os';
import path from 'path';
import { ROOT_DIR } from '#utils/workspace-config.js';
import { codexRoleFiles, parseRole, renderCodexRole } from '../roles.js';

const REVIEWER = `---
name: reviewer
description: Clean-context reviewer. Works from the "BRIEF" file.
tools: Read, Grep, Glob, Bash, Edit
---

# Reviewer

Follow the brief. Paths look like C:\\\\work and quotes like """ stay.
`;

describe('parseRole', () => {
  test('should read the frontmatter and the body', () => {
    expect(parseRole(REVIEWER, 'reviewer.md')).toEqual({
      name: 'reviewer',
      description: 'Clean-context reviewer. Works from the "BRIEF" file.',
      tools: ['Read', 'Grep', 'Glob', 'Bash', 'Edit'],
      body: '# Reviewer\n\nFollow the brief. Paths look like C:\\\\work and quotes like """ stay.\n',
    });
  });

  test('should fall back to the file name, and to all tools without a tools line', () => {
    expect(
      parseRole('---\ndescription: D\n  - a list item\n---\nBody', 'planner.md')
    ).toEqual({
      name: 'planner',
      description: 'D',
      tools: null,
      body: 'Body',
    });
  });

  test('should return null for a file without frontmatter or a description', () => {
    expect(parseRole('# Just markdown', 'x.md')).toBeNull();
    expect(parseRole('---\nname: x\n---\nBody', 'x.md')).toBeNull();
  });
});

describe('renderCodexRole', () => {
  test('should write a Codex role file that can write when the role can', () => {
    const text = renderCodexRole(
      /** @type {import('../roles.js').Role} */ (
        parseRole(REVIEWER, 'reviewer.md')
      ),
      '.claude/agents/reviewer.md'
    );
    expect(text).toBe(
      [
        '# Generated by pnpm harness sync from .claude/agents/reviewer.md; do not edit.',
        'name = "reviewer"',
        'description = "Clean-context reviewer. Works from the \\"BRIEF\\" file."',
        'sandbox_mode = "workspace-write"',
        'developer_instructions = """',
        '# Reviewer',
        '',
        'Follow the brief. Paths look like C:\\\\\\\\work and quotes like ""\\" stay.',
        '"""',
        '',
      ].join('\n')
    );
  });

  test('should make a role read-only when it can only read', () => {
    const role = /** @type {import('../roles.js').Role} */ (
      parseRole(
        '---\nname: security-reviewer\ndescription: D\ntools: Read, Grep, Glob\n---\nB',
        'x.md'
      )
    );
    expect(renderCodexRole(role, 'x.md')).toContain(
      'sandbox_mode = "read-only"'
    );
  });

  test('should let a role with every tool write', () => {
    const role = /** @type {import('../roles.js').Role} */ (
      parseRole('---\nname: t\ndescription: D\n---\nB', 't.md')
    );
    expect(renderCodexRole(role, 't.md')).toContain(
      'sandbox_mode = "workspace-write"'
    );
  });
});

describe('codexRoleFiles', () => {
  test('should generate one Codex role per Claude agent file in the workspace', () => {
    const files = codexRoleFiles(ROOT_DIR);
    const names = fs
      .readdirSync(path.join(ROOT_DIR, '.claude/agents'))
      .filter((f) => f.endsWith('.md'))
      .map((f) => `.codex/agents/${f.replace(/\.md$/, '.toml')}`);
    expect(files.map((f) => f.file).sort()).toEqual(names.sort());
    expect(
      files.find((f) => f.file.endsWith('/reviewer.toml'))?.content
    ).toContain('name = "reviewer"');
  });

  test('should return nothing without an agents folder', () => {
    expect(codexRoleFiles(path.join(ROOT_DIR, 'no-such-dir'))).toEqual([]);
  });

  test('should skip files that are not roles', () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'roles-'));
    const dir = path.join(root, '.claude/agents');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(
      path.join(dir, 'a.md'),
      '---\nname: a\ndescription: D\n---\nB'
    );
    fs.writeFileSync(path.join(dir, 'notes.md'), '# not a role');
    fs.writeFileSync(path.join(dir, 'b.txt'), 'x');
    expect(codexRoleFiles(root).map((f) => f.file)).toEqual([
      '.codex/agents/a.toml',
    ]);
    fs.rmSync(root, { recursive: true, force: true });
  });
});
