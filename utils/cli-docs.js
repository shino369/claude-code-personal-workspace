#!/usr/bin/env node
/** Generate the workspace CLI reference from each command's built-in help. */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fence } from './agent/cli.js';
import { runIfMain } from './module-runner.js';
import { readIfExists, writeFileAtomic } from './task/store.js';
import { ROOT_DIR } from './workspace-config.js';

const REFERENCE_FILE = 'docs/cli.md';
const HELP = `Usage: pnpm docs:cli [--check]

Generate ${REFERENCE_FILE} from the workspace CLI help.

Options
  --check      Exit 1 if the reference is missing or out of date
  --help, -h  Show this help`;

const HELP_COMMANDS = {
  agent: '--help',
  harness: 'help',
  loop: '--help',
  memory: '--help',
  'skills:install': '--help',
  'skills:link': '--help',
  swarm: '--help',
  task: '--help',
  tools: '--help',
  'workspace:setup': '--help',
};
const CHECK_SCRIPT = 'workspace:check';
const NODE_CLI =
  /^\s*node\s+(?:(-[^;&|\r\n]*?)\s+)?(['"]?)(?:\.\/)?(utils\/(?:[a-z0-9-]+\/cli|skills-(?:install|link)|workspace-setup)\.js)\2(?=\s|$)/;

/**
 * @typedef {{ status: number | null, stdout: string | null }} HelpResult
 * @typedef {{
 *   rootDir: string,
 *   runHelp: (entry: string, arg: string, rootDir: string) => HelpResult,
 *   log: (line: string) => void,
 * }} Deps
 */

/** @param {string} entry @param {string} arg @param {string} rootDir */
function captureHelp(entry, arg, rootDir) {
  return spawnSync(process.execPath, [entry, arg], {
    cwd: rootDir,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
    timeout: 10_000,
    windowsHide: true,
  });
}

/** @param {string} text */
const normalizeNewlines = (text) => text.replaceAll('\r\n', '\n');

/**
 * Read a direct Node command and its script arguments. The inventory also
 * detects invocations with Node flags, but help capture uses fixed arguments.
 * @param {string} script
 */
function nodeEntry(script) {
  const match = NODE_CLI.exec(script);
  return match && !match[1]
    ? { entry: match[3], args: script.slice(match[0].length).trim() }
    : null;
}

/** @param {Pick<Deps, 'rootDir' | 'runHelp'>} deps */
function renderReference({ rootDir, runHelp }) {
  const { scripts } = /** @type {{ scripts: Record<string, string> }} */ (
    JSON.parse(fs.readFileSync(path.join(rootDir, 'package.json'), 'utf8'))
  );
  const documented = new Set([...Object.keys(HELP_COMMANDS), CHECK_SCRIPT]);
  for (const [name, script] of Object.entries(scripts)) {
    if (NODE_CLI.test(script) && !documented.has(name)) {
      throw new Error(
        `Missing help source for pnpm ${name}.\nFix: add it to utils/cli-docs.js.`
      );
    }
  }
  const setup = nodeEntry(scripts['workspace:setup']);
  const check = nodeEntry(scripts[CHECK_SCRIPT]);
  if (!check || check.entry !== setup?.entry || check.args !== '--check') {
    throw new Error(
      'pnpm workspace:check has changed.\nFix: update its help source in utils/cli-docs.js.'
    );
  }

  const sections = Object.entries(HELP_COMMANDS).map(([name, arg]) => {
    const source = nodeEntry(scripts[name]);
    if (!source || source.args) {
      throw new Error(
        `Cannot locate the Node entry point for pnpm ${name}.\nFix: update its help source in utils/cli-docs.js.`
      );
    }
    const { status, stdout } = runHelp(source.entry, arg, rootDir);
    const help = normalizeNewlines(stdout ?? '').trimEnd();
    if (status !== 0 || !help.startsWith('Usage:')) {
      throw new Error(
        `Could not read help for pnpm ${name}.\nFix: run pnpm ${name} ${arg} and repair the help output.`
      );
    }
    const names = name === 'workspace:setup' ? [name, CHECK_SCRIPT] : [name];
    const title = names.map((command) => `\`pnpm ${command}\``).join(' and ');
    const anchor = names
      .map((command) => `pnpm-${command.replaceAll(':', '')}`)
      .join('-and-');
    const marker = fence(help);
    return {
      link: `- [${title}](#${anchor})`,
      markdown: [`## ${title}`, '', `${marker}text`, help, marker].join('\n'),
    };
  });
  const otherScripts = Object.keys(scripts)
    .filter((name) => !documented.has(name))
    .sort()
    .map((name) => `- \`pnpm ${name}\``);

  return (
    [
      '# CLI reference',
      '<!-- Generated by pnpm docs:cli. -->',
      'Run `pnpm docs:cli` to refresh this reference from the workspace CLI help. Run `pnpm docs:cli --check` to check for drift.',
      '## Contents',
      [
        ...sections.map(({ link }) => link),
        '- [Other workspace scripts](#other-workspace-scripts)',
      ].join('\n'),
      ...sections.map(({ markdown }) => markdown),
      '## Other workspace scripts',
      otherScripts.join('\n'),
    ].join('\n\n') + '\n'
  );
}

/**
 * @param {{ argv?: string[], deps?: Partial<Deps> }} [options]
 * @returns {number}
 */
export function main({
  argv = process.argv.slice(2),
  deps: { rootDir = ROOT_DIR, runHelp = captureHelp, log = console.log } = {},
} = {}) {
  const [flag] = argv;
  if (argv.length === 1 && (flag === '--help' || flag === '-h')) {
    log(HELP);
    return 0;
  }
  const check = flag === '--check';
  if (argv.length > 1 || (flag !== undefined && !check)) {
    throw new Error(
      'Usage: pnpm docs:cli [--check]\nFix: run pnpm docs:cli --help.'
    );
  }

  const expected = renderReference({ rootDir, runHelp });
  const file = path.join(rootDir, REFERENCE_FILE);
  const current = readIfExists(file);
  if (current !== null && normalizeNewlines(current) === expected) {
    log(`✓ ${REFERENCE_FILE} is up to date`);
    return 0;
  }
  if (check) {
    log(
      `✗ ${REFERENCE_FILE} is ${current === null ? 'missing' : 'out of date'}\nFix: pnpm docs:cli`
    );
    return 1;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  writeFileAtomic(file, expected);
  log(`Wrote ${REFERENCE_FILE}`);
  return 0;
}

/* c8 ignore start - CLI entry point */
runIfMain(import.meta.url, () => {
  try {
    process.exitCode = main();
  } catch (error) {
    console.error('Error:', error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
});
/* c8 ignore stop */
